"""Office and presentation conversion engine (PPT/PPTX to PDF, JPG, PNG) using LibreOffice and Poppler."""

from __future__ import annotations

import logging
import shutil
from pathlib import Path
from typing import Any, Dict

from filetool.core.deps import resolver
from filetool.core.registry import Converter, OptionDefinition, registry
from filetool.core.utils import run_command, safe_temp_dir

logger = logging.getLogger("filetool.engines.office")

SLIDE_FORMATS = ("ppt", "pptx")

SLIDE_OPTIONS = {
    "dpi": OptionDefinition(
        name="dpi",
        label="Slide Image DPI",
        type=int,
        default=300,
        min_value=72,
        max_value=600,
        description="Resolution for rendered presentation slides",
    ),
}


def convert_slides_to_pdf(src: Path, dest: Path, options: Dict[str, Any]) -> Path:
    """Convert PPT or PPTX presentation to PDF using headless LibreOffice."""
    soffice = resolver.get_tool_path("soffice")

    with safe_temp_dir(prefix="filetool_slides_pdf_") as tmp_dir:
        cmd = [
            soffice,
            "--headless",
            "--convert-to", "pdf",
            "--outdir", str(tmp_dir),
            str(src),
        ]
        res = run_command(cmd, timeout=90.0)
        expected_pdf = tmp_dir / f"{src.stem}.pdf"
        if not expected_pdf.exists():
            raise RuntimeError(f"Presentation to PDF conversion failed: {res.stderr_tail()}")
        shutil.copy2(expected_pdf, dest)

    return dest


def convert_slides_to_images(src: Path, dest: Path, options: Dict[str, Any]) -> Path:
    """
    Convert PPT or PPTX presentation slides to high-resolution JPG or PNG (300 DPI).
    Uses LibreOffice to produce intermediate PDF, then pdftoppm to render slide images.
    """
    soffice = resolver.get_tool_path("soffice")
    pdftoppm = resolver.get_tool_path("pdftoppm")
    out_ext = dest.suffix.lower().lstrip(".")
    dpi = int(options.get("dpi", 300))

    with safe_temp_dir(prefix="filetool_slides_img_") as tmp_dir:
        # Step 1: Render slides to PDF
        cmd = [soffice, "--headless", "--convert-to", "pdf", "--outdir", str(tmp_dir), str(src)]
        res = run_command(cmd, timeout=90.0)
        intermediate_pdf = tmp_dir / f"{src.stem}.pdf"
        if not intermediate_pdf.exists():
            raise RuntimeError(f"Failed to generate intermediate PDF from presentation: {res.stderr_tail()}")

        # Step 2: Render PDF pages to PNG or JPEG using pdftoppm at 300 DPI
        fmt_flag = "-png" if out_ext == "png" else "-jpeg"
        prefix = tmp_dir / "slide"
        render_cmd = [pdftoppm, fmt_flag, "-r", str(dpi), str(intermediate_pdf), str(prefix)]
        render_res = run_command(render_cmd, timeout=60.0)
        if not render_res.success:
            raise RuntimeError(f"Failed rendering slides to images: {render_res.stderr_tail()}")

        # Locate rendered slide images
        slide_images = sorted(tmp_dir.glob("slide-*.*"))
        if not slide_images:
            raise RuntimeError("No slide images were generated by pdftoppm")

        # Copy first slide to target dest
        shutil.copy2(slide_images[0], dest)

        # If multiple slides exist, save additional slides alongside destination:
        # e.g., 'presentation (Slide 2).png'
        if len(slide_images) > 1:
            dest_dir = dest.parent
            dest_stem = dest.stem
            for idx, img_path in enumerate(slide_images[1:], start=2):
                sibling_dest = dest_dir / f"{dest_stem} (Slide {idx}).{out_ext}"
                shutil.copy2(img_path, sibling_dest)

    return dest


def register_office_converters() -> None:
    """Register presentation and office converters."""
    # PPT/PPTX to PDF
    registry.register(
        Converter(
            id="slides_to_pdf",
            name="Slides (PPT/PPTX) to PDF",
            input_formats=SLIDE_FORMATS,
            output_format="pdf",
            category="Slides",
            convert_fn=convert_slides_to_pdf,
            required_tools=("soffice",),
            description="Convert PPT/PPTX presentation to vector PDF",
        )
    )

    # PPT/PPTX to PNG
    registry.register(
        Converter(
            id="slides_to_png",
            name="Slides (PPT/PPTX) to PNG",
            input_formats=SLIDE_FORMATS,
            output_format="png",
            category="Slides",
            convert_fn=convert_slides_to_images,
            options=SLIDE_OPTIONS,
            required_tools=("soffice", "pdftoppm"),
            description="Render presentation slides to 300 DPI PNG images",
        )
    )

    # PPT/PPTX to JPG
    registry.register(
        Converter(
            id="slides_to_jpg",
            name="Slides (PPT/PPTX) to JPG",
            input_formats=SLIDE_FORMATS,
            output_format="jpg",
            category="Slides",
            convert_fn=convert_slides_to_images,
            options=SLIDE_OPTIONS,
            required_tools=("soffice", "pdftoppm"),
            description="Render presentation slides to 300 DPI JPG images",
        )
    )


# Automatically register on import
register_office_converters()
